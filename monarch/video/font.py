_FALLBACK = _FONT["?"]

# pre-split into row ints at import: char -> [7 rows of 5-bit ints]
_ROWS: dict[str, list[int]] = {
    ch: [int(row.replace(" ", ""), 2) for row in bits.split()] for ch, bits in _FONT.items()
}

_FALLBACK = _ROWS["?"]


def glyph_rows(ch: str) -> list[int]:
    """Return the 7 bitmap rows (5-bit ints, MSB = left pixel) for ``ch``."""
    return _ROWS.get(ch.upper(), _ROWS.get(ch, _FALLBACK))


def has_glyph(ch: str) -> bool:
    return ch.upper() in _ROWS


def text_width(text: str, scale: int = 1) -> int:
    """Rendered width in pixels (last glyph carries no trailing gap)."""
    if not text:
        return 0
    return (len(text) * ADVANCE - 1) * scale


def wrap_text(text: str, max_width_px: int, scale: int = 1) -> list[str]:
    """Greedy word wrap against the rendered pixel width."""
    max_chars = max(1, (max_width_px + ADVANCE - 1) // (ADVANCE * scale))
    out: list[str] = []
    for paragraph in (text or "").splitlines():
        words = paragraph.split()
        if not words:
            out.append("")
            continue
        line = words[0]
        for w in words[1:]:
            if len(line) + 1 + len(w) <= max_chars:
                line += " " + w
            else:
                out.append(line)
                line = w
        out.append(line)
    return out or [""]
